from __future__ import annotations

import argparse
from pathlib import Path


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Evaluate LLM batch answers against ground-truth answers.csv"
    )
    parser.add_argument(
        "--batch",
        type=Path,
        required=True,
        help="Path to batch_*.csv generated by batch runner",
    )
    parser.add_argument(
        "--ground-truth",
        type=Path,
        default=None,
        help="Optional path to ground-truth answers CSV (defaults to dataset answers.csv)",
    )
    parser.add_argument(
        "--out-json",
        type=Path,
        default=None,
        help="Optional JSON report path",
    )
    parser.add_argument(
        "--out-csv",
        type=Path,
        default=None,
        help="Optional per-question CSV metrics path",
    )
    parser.add_argument(
        "--strict-source-id",
        action="store_true",
        help="Fail if batch and ground-truth source_id sets do not exactly match",
    )
    return parser
